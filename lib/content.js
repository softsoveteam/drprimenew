export function faqAnswerText(faq) {
  if (faq.a) return faq.a;
  const bullets = (faq.bullets || [])
    .map((bullet) => `${bullet.title}: ${bullet.text}`)
    .join(" ");
  return [faq.intro, bullets].filter(Boolean).join(" ");
}
